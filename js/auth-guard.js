// ─────────────────────────────────────────────────────────────
// js/auth-guard.js — ยามเฝ้าหน้า: ต้องล็อกอินก่อนถึงจะเปิดหน้านี้ได้
// แปะไว้ทุกหน้าของระบบ (ยกเว้น login.html / register.html)
// สัปดาห์ที่ 7: แค่เช็คว่าล็อกอินหรือยัง ยังไม่แยกสิทธิ์ตามบทบาท
//
// window.รอสถานะล็อกอิน คือ Promise ที่ resolve พร้อมส่ง user กลับไป
// ทันทีที่ Firebase ยืนยันแน่ชัดแล้วว่าล็อกอินอยู่ — สคริปต์หน้าไหนจะอ่าน
// Firestore ต้องรอ Promise นี้ก่อนค่อยเริ่มอ่านจริง กันไม่ให้ยิง request
// ออกไปก่อน auth token พร้อม ซึ่งจะโดน Security Rules ปฏิเสธ
// ─────────────────────────────────────────────────────────────

window.รอสถานะล็อกอิน = new Promise(function (resolve) {
  var เลิกฟัง = firebase.auth().onAuthStateChanged(function (user) {
    เลิกฟัง();
    if (!user) {
      location.href = "login.html";
      return;   // ไม่ resolve ต่อ เพราะหน้ากำลังจะเปลี่ยนไปที่อื่นอยู่แล้ว
    }
    resolve(user);
  });
});
